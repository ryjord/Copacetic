/**
 * Turns publicsuffix.org's list into the compact module the address bar uses.
 *
 * Run with `npm run generate:psl`. The output is committed, so a build never
 * depends on publicsuffix.org being reachable — and so a change to the list is
 * a reviewable diff rather than something that silently shifts under a release.
 */
import { writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';

const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = new URL('../electron/shared/public-suffix-list.ts', import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);

const normal = [];
const wildcard = [];
const exception = [];

/**
 * The list publishes internationalised rules in Unicode (`公司.cn`), but a URL
 * always reports its hostname in punycode (`xn--55qx5d.cn`). Encoding here
 * means the lookup is a plain string comparison rather than a conversion on
 * every keystroke.
 */
const encode = (rule) => {
  const encoded = domainToASCII(rule);
  if (!encoded) throw new Error(`Could not encode rule: ${rule}`);
  return encoded;
};

for (const raw of (await response.text()).split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('//')) continue;
  if (line.startsWith('!')) exception.push(encode(line.slice(1)));
  else if (line.startsWith('*.')) wildcard.push(encode(line.slice(2)));
  else normal.push(encode(line));
}

if (normal.length < 5000) throw new Error(`Only ${normal.length} rules parsed; the format probably changed.`);

const stamp = new Date().toISOString().slice(0, 10);
const pack = (rules) => JSON.stringify(rules.sort().join(' '));

writeFileSync(
  OUT,
  `/**
 * The IANA Public Suffix List, from ${SOURCE}
 *
 * Generated by scripts/generate-public-suffix-list.mjs — do not edit by hand.
 * Fetched ${stamp}: ${normal.length} rules, ${wildcard.length} wildcard, ${exception.length} exception.
 *
 * Stored as space-separated strings rather than arrays of literals: it is a
 * fraction of the source size, and splitting once at module load is cheaper
 * than parsing ten thousand string literals.
 */

const NORMAL = ${pack(normal)};
const WILDCARD = ${pack(wildcard)};
const EXCEPTION = ${pack(exception)};

export const PUBLIC_SUFFIX_RULES: ReadonlySet<string> = new Set(NORMAL.split(' '));
export const PUBLIC_SUFFIX_WILDCARDS: ReadonlySet<string> = new Set(WILDCARD.split(' '));
export const PUBLIC_SUFFIX_EXCEPTIONS: ReadonlySet<string> = new Set(EXCEPTION.split(' '));
`,
  'utf8',
);

console.log(`Wrote ${normal.length} + ${wildcard.length} wildcard + ${exception.length} exception rules.`);
